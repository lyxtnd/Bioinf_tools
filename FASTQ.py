# Все функции возвращают ax — это удобно, если вызывающий код хочет
# дорисовать что-то поверх (например, горизонтальную линию на Q=20).


def plot_per_base_quality(parser, ax=None):
    """Нарисовать график «качество по позициям прочтения».

    ЧТО НАРИСОВАНО:
        По оси X — позиция нуклеотида в прочтении (0, 1, 2, ... до
        максимальной длины). По оси Y — оценка Phred (0–40+).

        Три элемента:
          * Закрашенная область — диапазон Q1..Q3. Показывает, где
            лежит «средняя масса» записей в каждой позиции. Широкая
            область = большой разброс качества.
          * Сплошная линия — медиана. Типичное качество в позиции.
          * Пунктирная линия — среднее. Обычно близко к медиане;
            если сильно расходится — есть выбросы.

    Аргументы:
        parser (FastqParser): источник данных. Внимание: парсер
            одноразовый — после вызова его нельзя использовать
            ещё раз. Если нужно несколько графиков — создайте
            несколько парсеров (см. plot_all).
        ax (matplotlib.axes.Axes | None): ось для рисования.
            Если None — создаётся новая фигура.

    Возвращает:
        matplotlib.axes.Axes: ось с нарисованным графиком.
    """
    if ax is None:
        # figsize=(10, 4) — широкий и невысокий график, как в FastQC.
        # _ — потому что fig нам тут не нужен (нужен только ax).
        _, ax = plt.subplots(figsize=(10, 4))

    stats = parser.per_base_quality()
    x = stats["positions"]

    # Закрашенная область между Q1 и Q3.
    # alpha=0.3 — полупрозрачная, чтобы линии поверх были видны.
    ax.fill_between(x, stats["q1"], stats["q3"], alpha=0.3, label="Q1-Q3")

    # Медиана и среднее.
    ax.plot(x, stats["median"], label="Median", linewidth=1.5)
    ax.plot(x, stats["mean"], "--", label="Mean", linewidth=1.5)

    # Подписи осей и заголовок.
    ax.set_xlabel("Position in read (bp)")
    ax.set_ylabel("Phred quality score")
    ax.set_title("Per base sequence quality")

    # Легенда в левом нижнем углу (там обычно пусто).
    # fontsize=8 — чтобы не закрывала данные.
    ax.legend(loc="lower left", fontsize=8)

    # Сетка полупрозрачная — не отвлекает от линий.
    ax.grid(alpha=0.3)
    return ax


def plot_per_base_content(parser, ax=None):
    """Нарисовать график «состав нуклеотидов по позициям прочтения».

    Что нарисовано:

    - По оси X — позиция в прочтении (0, 1, 2, ... до максимальной длины).
    - По оси Y — доля основания в процентах (0–100).
    - Четыре линии: A (зелёная), C (синяя), G (оранжевая), T (красная).
    - Цвета выбраны как в FastQC — по ним легко сверяться.

    Аргументы:
        parser (FastqParser): источник данных. Внимание: парсер одноразовый — после вызова его нельзя использовать ещё раз. Если нужно несколько графиков — создайте несколько парсеров (см. plot_all).
        ax (matplotlib.axes.Axes | None): ось для рисования. Если None — создаётся новая фигура.

    Возвращает:
        matplotlib.axes.Axes: ось с нарисованным графиком.
    """

    if ax is None:
        _, ax = plt.subplots(figsize=(10, 4))

    content = parser.per_base_content()

    # X-координаты общие для всех четырёх линий — это позиции в прочтении.
    x = content["positions"]

    # Цвета — как в FastQC: A зелёная, C синяя, G оранжевая, T красная.
    colors = {"A": "green", "C": "blue", "G": "orange", "T": "red"}

    for base, color in colors.items():
        # content[base] — список долей от 0.0 до 1.0.
        # Умножаем на 100, чтобы по оси Y были проценты (0–100),
        ax.plot(x,[v * 100 for v in content[base]],label=base,color=color,linewidth=1.2)


    ax.set_xlabel("Position in read (bp)")   # bp = base pairs
    ax.set_ylabel("Base content (%)")

    # Фиксируем диапазон Y от 0 до 100. Без этого matplotlib подберёт
    ax.set_ylim(0, 100)

    ax.set_title("Per base sequence content")

    # Легенда. fontsize=8 — чтобы не закрывала линии. Местоположение
    # не указано -> matplotlib выберет «лучшее» место (best), обычно
    # там, где меньше всего данных. Для этого графика часто это
    # правый верхний или правый нижний угол.
    ax.legend(loc='upper right',fontsize=8)

    # Полупрозрачная сетка — помогает читать значения, но не
    # перебивает линии.
    ax.grid(alpha=0.3)

    # Возвращаем ось 
    return ax


def plot_length_distribution(parser, ax=None):
    """Нарисовать гистограмму длин прочтений (sequence length distribution).

    ЧТО НАРИСОВАНО:
        По оси X — длина прочтения в парах оснований (bp). Каждое
        уникальное значение длины — отдельный столбик.
        По оси Y — сколько записей имеют такую длину.

    Аргументы:
        parser (FastqParser): источник данных. Внимание: парсер
            одноразовый — после вызова его нельзя использовать
            ещё раз. Каждый вызов plot_* требует нового парсера
            (см. plot_all, который принимает фабрику).
        ax (matplotlib.axes.Axes | None): ось для рисования.
            Если None — создаётся новая фигура.

    Возвращает:
        matplotlib.axes.Axes: ось с нарисованным графиком.
    """
    
    if ax is None:
        _, ax = plt.subplots(figsize=(10, 4))

    dist = parser.length_distribution()

    lengths = list(dist.keys())
    counts = list(dist.values())

    # ax.bar(x, height) — вертикальная столбчатая диаграмма.
    #   x      = позиции столбиков по горизонтали (длины);
    #   height = высоты столбиков (количества).
    ax.bar(lengths, counts, color="purple")

    ax.set_xlabel("Sequence length (bp)")   # bp = base pairs
    ax.set_ylabel("Number of reads")


    ax.set_title("Sequence length distribution")


    # axis="y" — рисуем линии только параллельно оси X (горизонтальные).
    # alpha=0.3 — полупрозрачная, чтобы не перебивать цвет столбиков.
    ax.grid(alpha=0.3, axis="y")

    # Возвращаем ось 
    return ax


