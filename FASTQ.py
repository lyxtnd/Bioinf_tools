def _mean(values)-> float:
    """Среднее арифметическое списка.

    Аргументы:
        values (list[number]): список чисел. Может быть пустым.

    Возвращает:
        float: sum(values) / len(values), либо NaN, если список пуст.

    """
    if not values:
        return float("NaN")
    return sum(values) / len(values)


def _percentile(values, p)-> float:
    """Перцентиль p (0–100) с линейной интерполяцией.

    Что такое перцентиль:
        Перцентиль p — это значение, ниже которого лежит p% данных.
        Медиана — это 50-й перцентиль, Q1 — 25-й, Q3 — 75-й.

    Алгоритм (метод линейной интерполяции):
        1. Отсортировать список.
        2. Найти позицию k = (n - 1) * p / 100 в отсортированном массиве.
        3. Если k целое — вернуть s[k]. Иначе — линейно
           проинтерполировать между s[floor(k)] и s[ceil(k)].

    Аргументы:
        values (list[number]): список чисел. Может быть пустым.
        p (float): перцентиль от 0 до 100.

    Возвращает:
        float: значение перцентиля, либо NaN для пустого списка.

    """
    if not values:
        return float("nan")
    s = sorted(values)
    if len(s) == 1:
        return float(s[0])
    # Позиция перцентиля 
    k = (len(s) - 1) * (p / 100.0)
    lo = math.floor(k)
    hi = math.ceil(k)
    # Точное попадание — возвращаем как есть.
    if lo == hi:
        return float(s[int(k)])
    # Иначе интерполируем между соседними значениями.
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def _median(values)-> float:
    """Медиана — это просто 50-й перцентиль."""
    return _percentile(values, 50)


