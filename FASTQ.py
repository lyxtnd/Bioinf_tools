
from typing import Iterator

"""
Модуль для чтения и анализа файлов в формате FASTQ.

===============================================================================
ЧТО ТАКОЕ FASTQ
===============================================================================

FASTQ — текстовый формат, в котором хранят прочтения (reads) секвенирования
ДНК. Каждая запись занимает РОВНО 4 строки:

    @READ_1                    <- заголовок, начинается с '@'
    GATTTGGGGTTCAAAGCAGT...    <- последовательность нуклеотидов (A/C/G/T/N)
    +                          <- разделитель, начинается с '+'
    !''*((((***+))%%%++)(%%%   <- строка качества (по 1 символу на букву)


===============================================================================
ЧТО ТАКОЕ КАЧЕСТВО (Phred score)
===============================================================================

Каждый символ в строке качества — это ASCII-символ, кодирующий число.
Чтобы получить оценку Phred (Q), надо вычесть 33 (в старых версиях Phred+33):

    Q = ord(символ) - 33

Примеры:
    '!' (ASCII 33)  ->  Q = 0     (очень плохое качество)
    '+' (ASCII 43)  ->  Q = 10
    '5' (ASCII 53)  ->  Q = 20
    'I' (ASCII 73)  ->  Q = 40    (отличное качество, стандарт для Illumina)

Чем больше Q, тем меньше вероятность, что нуклеотид определён неверно:
    Q=10  ->  ошибка ~1 из 10
    Q=20  ->  ошибка ~1 из 100
    Q=30  ->  ошибка ~1 из 1000
    Q=40  ->  ошибка ~1 из 10000

===============================================================================
ЗАЧЕМ НУЖЕН ЭТОТ МОДУЛЬ
===============================================================================

1. Читать FASTQ-файлы (в т.ч. сжатые .gz).
2. Считать базовую статистику.
3. Строить «отчёты качества» в стиле FastQC: качество по позициям,
   состав нуклеотидов по позициям, распределение длин.
"""

   
