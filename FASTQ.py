class FastqRecord:
    """Одна запись FASTQ: заголовок, последовательность и качество.

    Атрибуты:
        header (str): заголовок БЕЗ ведущего '@'. Например "SRR001.1 read1".
        sequence (str): последовательность нуклеотидов, например "ACGTACGT". Может содержать 'N' (неопределённый нуклеотид).
        quality (str): строка качества, длина совпадает с sequence. Каждый символ — ASCII-код Phred+33.
    """

    def __init__(self, header, sequence, quality):
        self.header = header
        self.sequence = sequence
        self.quality = quality

    @property
    def length(self)-> int:
        """Длина последовательности в нуклеотидах (bp — base pairs)."""
        return len(self.sequence)

    def phred_scores(self)-> list[int]:
        """Превратить строку качества в список числовых оценок Phred."""
        result = []
        for c in self.quality:
            result.append(ord(c) - 33)
        return result

    def __repr__(self)-> str:
        """Короткое представление для отладки"""
        return f"FastqRecord({self.header!r}, len={self.length})"


