class FastqParser:
    """Потоковый парсер FASTQ-файла: отдаёт записи по одной.

    Атрибуты:
        path (str): путь к файлу.
        compressed (bool): True, если файл сжат gzip.
    """

    def __init__(self, path, compressed=None):
        """Проверить существование файла и запомнить настройки.

        Аргументы:
            path (str): путь к FASTQ-файлу.
            compressed (bool): True для .gz-файлов. 

        Исключения:
            FileNotFoundError: если файла по указанному пути нет.
        """
        if not os.path.exists(path):
            raise FileNotFoundError(f"Файл не найден: {path}")
        self.path = path
        self.compressed = compressed

    def _open(self):
        """Открыть файл для построчного чтения (с gzip или без).

        Возвращает файловый объект, который поддерживает .readline() и
        корректно закрывается через with. Логика выбора:

          * compressed=True  -> gzip.open(..., "rt")
            Режим "rt" = read text: gzip сам распаковывает на лету и отдаёт
            строки как обычный текстовый файл. Без "t" мы получили бы bytes,
            а нам нужны str.

          * compressed=False -> open(..., "r", encoding="utf-8")
            Указываем кодировку явно, чтобы не зависеть от локали системы.
            FASTQ — почти всегда ASCII, UTF-8 его надмножество, так что
            безопасно.

        """
        if self.compressed:
            return gzip.open(self.path, "rt")
        return open(self.path, "r", encoding="utf-8")

    def __iter__(self)-> Iterator[FastqRecord]:
        """
        Что делает:
            1. Открывает файл.
            2. В цикле читает по 4 строки (заголовок, последовательность,
               разделитель, качество).
            3. Проверяет корректность записи.
            4. yield'ит готовый FastqRecord и «забывает» его.

        ВАЖНО: заголовок отдаётся БЕЗ ведущего '@'. Разделитель '+'
        после проверки отбрасывается — он не несёт информации.
        """
        with self._open() as f:
            while True:
                header = f.readline()
                if not header:
                    return
                seq = f.readline()
                plus = f.readline()
                qual = f.readline()

                if not (seq and plus and qual):
                    raise ValueError(f"Обрыв записи на строке: {header!r}")

                header = header.strip()
                seq = seq.strip()
                qual = qual.strip()

                if not header.startswith("@"):
                    raise ValueError(
                        f"Заголовок должен начинаться с '@': {header!r}"
                    )
                
                if not plus.startswith("+"):
                    raise ValueError(
                        f"Третья строка должна начинаться с '+': {plus!r}"
                    )
                
                if len(seq) != len(qual):
                    raise ValueError(
                        f"seq и qual разной длины в {header!r}: "
                        f"{len(seq)} != {len(qual)}"
                    )

                yield FastqRecord(header[1:], seq, qual)

    # ------------------------------------------------------------------
    # СТАТИСТИКА
    # ------------------------------------------------------------------

    def count_sequences(self)-> int:
        """Посчитать общее число записей в файле."""
        n = 0
        for _ in self:
            n += 1
        return n

    def average_length(self)-> float:
        """Средняя длина последовательности по всем записям.

        Возвращает:
            float: суммарная длина / число записей.
            Если файл пуст — 0.0 (а не деление на ноль).
        """
        total = 0
        n = 0
        for rec in self:
            total += rec.length
            n += 1
        return total / n if n else 0.0

    def length_distribution(self)-> dict[int, int]:
        """Сколько записей каждой длины встречается в файле.

        Возвращает:
            dict[int, int]: {длина: количество_записей}.
            Отсортирован по возрастанию длины.

        Пример:
            {50: 1000, 51: 2500, 52: 500} — значит 1000 записей длиной
            50 bp, 2500 записей длиной 51 bp и т.д.
        """
        counter = Counter()
        for rec in self:
            counter[rec.length] += 1
        # counter.items() возвращает view (представление) — пары (ключ, значение)
        # sorted возвращает отсортированный список пар
        # dict раскладывает его обратно в словарь,сохраняя порядок вставки
        return dict(sorted(counter.items()))

    

    # ------------------------------------------------------------------
    # ДАННЫЕ ДЛЯ ГРАФИКОВ
    # ------------------------------------------------------------------

    def per_base_quality(self)-> dict:
        """Статистика качества по КАЖДОЙ позиции прочтения.

        Возвращает:
            dict с ключами:
                positions (list[int])   — [0, 1, 2, ...] до максимальной длины;
                mean      (list[float]) — среднее Q по позиции;
                median    (list[float]) — медиана Q;
                q1        (list[float]) — 25-й перцентиль;
                q3        (list[float]) — 75-й перцентиль.

        """
        # per_pos[i] — список Q-значений в позиции i по всем записям.
        per_pos = []
        for rec in self:
            scores = rec.phred_scores()
            # Если запись длиннее всех предыдущих — досоздаём пустые
            # списки под новые позиции.
            while len(per_pos) < len(scores):
                per_pos.append([])
            # Раскладываем оценки по позициям.
            for i, q in enumerate(scores):
                per_pos[i].append(q)

        positions = list(range(len(per_pos)))
        return {
            "positions": positions,
            "mean": [_mean(v) for v in per_pos],
            "median": [_median(v) for v in per_pos],
            "q1": [_percentile(v, 25) for v in per_pos],
            "q3": [_percentile(v, 75) for v in per_pos],
        }

    def per_base_content(self) -> dict:
        """Доля каждой буквы (A, C, G, T) в КАЖДОЙ позиции прочтения.

        Идея та же, что в per_base_quality, но считаем не Q-значения,
        а сколько раз в позиции i встретилась каждая буква.

        Возвращает:
            dict с ключами:

            - positions (list[int]) — [0, 1, 2, ...];
            - A, C, G, T — списки долей от 0.0 до 1.0 (сумма по позиции = 1, если нет 'N' и прочих не-ACGT символов).
        """
        per_pos = []
        for rec in self:
            seq = rec.sequence.upper()
            # Если текущая запись длиннее всех предыдущих — досоздаём
            # пустые Counter'ы под новые позиции.
            while len(per_pos) < len(seq):
                per_pos.append(Counter())
            for i, ch in enumerate(seq): # enumerate(seq) даёт пары (индекс, символ): (0, 'A'), (1, 'C')...
                per_pos[i][ch] += 1 # увеличиваем счётчик буквы ch в позиции i

        result = {"positions": list(range(len(per_pos)))}
        # Внешний цикл — по буквам. Внутри — по позициям.
        for base in ("A", "C", "G", "T"):
            values = []
            for c in per_pos:  # c — Counter букв в одной позиции
                total = sum(c.values())   # все символы в позиции, включая N
                values.append(c.get(base, 0) / total if total else 0.0) # c.get(base, 0) возвращает значение по ключу base, а если такого ключа нет — возвращает 0 
            result[base] = values # кладёт список values в словарь result под ключом base.
        return result


