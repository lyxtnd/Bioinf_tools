def plot_all(parser_factory, output_path):
    """Собрать все три графика на одной фигуре и (опционально) сохранить PNG.

    ПОЧЕМУ ПАРАМЕТР — ФАБРИКА, А НЕ ПАРСЕР:
        FastqParser одноразовый: после полного прохода
        его итератор исчерпан. Каждый из трёх графиков требует СВОЕГО
        прохода по файлу, а значит — своего парсера.

    Аргументы:
        parser_factory (): функция без аргументов, возвращающая
            НОВЫЙ FastqParser. 

        output_path (str): путь для сохранения PNG.
           

    Возвращает:
        matplotlib.figure.Figure: фигура с тремя панелями.
    """
    
    # plt.subplots(3, 1, figsize=(11, 12)):
    #   3, 1        — сетка 3 строки × 1 столбец (три панели друг под другом).
    #   figsize     — размер фигуры в дюймах: 11 дюймов в ширину,
    #                 12 в высоту. При dpi=120 (плотность 120 точек на дюйм) итоговый PNG
    #                 будет ~1320×1440 пикселей.
    #
    # subplots возвращает:
    #   fig  — Figure (вся картинка, контейнер);
    #   axes — массив из трёх осей: axes[0], axes[1], axes[2].
    #
    # Здесь, в отличие от одиночных plot_*, мы ОБЯЗАТЕЛЬНО сохраняем
    # и fig, и axes: fig нужен для tight_layout и savefig, axes —
    # чтобы передать каждую панель в соответствующую plot_* функцию.
    fig, axes = plt.subplots(3, 1, figsize=(11, 12))

    # Рисуем три графика — по одному на каждую ось.
    # Каждый вызов parser_factory() создаёт НОВЫЙ FastqParser.
    # Почему передаём ax=axes[i]:
    #   Без этого каждая plot_* функция создала бы СВОЮ фигуру.
    #   Мы получили бы три отдельных окна вместо
    #   одной фигуры с тремя панелями.
 
    plot_per_base_quality(parser_factory(), ax=axes[0])
    plot_per_base_content(parser_factory(), ax=axes[1])
    plot_length_distribution(parser_factory(), ax=axes[2])

    # Убираем наложения подписей.
    # tight_layout() автоматически подбирает отступы между панелями
    # так, чтобы ничего не перекрывалось. 
    fig.tight_layout()

    # Сохраняем PNG.
    # savefig с параметрами:
    #   dpi=120 — 120 точек на дюйм. При figsize=(11, 12)
    #             итоговый PNG ~1320×1440 пикселей. Этого хватает,
    #             чтобы читать подписи и мелкие детали, но файл
    #             не раздувается до мегабайт. 
    #
    #   bbox_inches="tight" — обрезать пустые поля вокруг фигуры.
    #             Без этого matplotlib сохраняет фигуру целиком
    #             с большими белыми полями по краям (особенно
    #             если подписи выходят за пределы «холста»).

    fig.savefig(output_path, dpi=120, bbox_inches="tight")

    # plt.close(fig) — ОБЯЗАТЕЛЬНО после сохранения.
    # Зачем закрывать:
    #   matplotlib хранит все созданные фигуры в глобальном реестре
    #   (plt.get_fignums()), пока их явно не закроют. Если не закрывать фигуры,
    #   произойдет утечка.
    plt.close(fig)

    # Возвращаем fig 
    return fig

